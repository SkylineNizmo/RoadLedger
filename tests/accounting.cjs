const assert=require('node:assert/strict');
const {reconcile}=require('../roadledger-accounting.js');
const loads=[{id:'a',expenses:100},{id:'b',expenses:50}];
const expense=(amount,loadExpenseId='',payer='business')=>({amount,loadExpenseId,payer});
const verify=(entries,expected)=>{const before=JSON.stringify({loads,entries});const result=reconcile(loads,entries);for(const [key,value] of Object.entries(expected))assert.equal(result[key],value,key);assert.equal(JSON.stringify({loads,entries}),before);return result};
verify([expense(100)],{total:250,business:250,overlap:0});
verify([expense(100,'a')],{total:150,business:150,overlap:100});
verify([expense(30,'a'),expense(40,'a')],{total:150,overlap:70});
verify([expense(80,'a'),expense(60,'a')],{total:190,overlap:100});
verify([expense(130,'a')],{total:180,overlap:100});
verify([expense(100,'missing')],{total:250,overlap:0});
verify([expense(100,'a','driver'),expense(10,'a','reimbursed')],{total:260,business:150,personal:100,overlap:0});
verify([expense(100,'a'),expense(50,'b'),expense(7)],{total:157,overlap:150});
verify([expense('100','a')],{total:150,overlap:100});
assert.equal(reconcile([{id:'a',expenses:0.3}],[expense(0.1,'a'),expense(0.2,'a')]).total,0.3);
assert.equal(reconcile([{id:'a',expenses:0}],[expense(12,'a')]).total,12);
assert.equal(reconcile([],[expense(12,'a')]).total,12);
const forward=verify([expense(80,'a'),expense(60,'a')],{}),reverse=verify([expense(60,'a'),expense(80,'a')],{});assert.equal(forward.total,reverse.total);assert.equal(forward.business,reverse.business);
console.log('PASS: explicit matching, partial/split/excess coverage, separate costs, multiple loads, payer boundaries, missing loads, cents, immutable input records, and order-independent totals.');
